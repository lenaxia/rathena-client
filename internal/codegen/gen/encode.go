// EncodeInput describes a single semantic action to generate an encode function for.
// Only send-direction (C→S) actions should be passed here.
type EncodeInput struct {
	Action       *semantics.Action
	VersionTable preprocess.VersionTable
}

// GenerateEncodeFile generates the Go source for pkg/encode/<action_name>.go.
//
// For fixed-size packets, the function returns [N]byte.
// For variable-size packets, the function returns []byte.
//
// Field names and Go types are derived directly from the rAthena struct layout.
func GenerateEncodeFile(input EncodeInput) (filename string, src string, err error) {
	a := input.Action
	if a == nil {
		return "", "", fmt.Errorf("nil action")
	}
	if a.Name == "" {
		return "", "", fmt.Errorf("action has empty name")
	}
	if len(a.Implementations) == 0 {
		return "", "", fmt.Errorf("action %s: no implementations", a.Name)
	}

	// Filter to C→S implementations only before deciding single vs. multi path.
	// This ensures that a mixed-direction action (e.g. one CZ + one ZC impl) is
	// treated as a single-impl encode rather than generating a broken empty dispatcher.
	sendImpls := make([]semantics.Implementation, 0, len(a.Implementations))
	for _, impl := range a.Implementations {
		if isSendStruct(impl.StructName) {
			sendImpls = append(sendImpls, impl)
		}
	}
	if len(sendImpls) == 0 {
		return "", "", fmt.Errorf("action %s: no send-direction implementations", a.Name)
	}

	structName := actionNameToGoIdent(a.Name)
	filename = actionNameToFilename(a.Name)

	var sb strings.Builder
	sb.WriteString("// Code generated by internal/codegen. DO NOT EDIT.\n\n")
	sb.WriteString("package encode\n\n")
	sb.WriteString("import (\n")
	sb.WriteString("\t\"github.com/lenaxia/rathena-client/pkg/send\"\n")
	sb.WriteString(")\n\n")

	if len(sendImpls) == 1 {
		impl := &sendImpls[0]
		layout := resolveLayout(impl.StructName, impl.PacketverMin, input.VersionTable)
		if layout == nil {
			return "", "", fmt.Errorf("action %s: no layout for struct %s", a.Name, impl.StructName)
		}

		funcSrc := generateEncodeFunc(structName, impl, layout)
		sb.WriteString(funcSrc)
	} else {
		// Build a synthetic action containing only the send impls for the dispatcher.
		sendAction := &semantics.Action{Name: a.Name, Implementations: sendImpls}
		dispatchSrc := generateEncodeDispatcher(structName, sendAction, input.VersionTable)
		sb.WriteString(dispatchSrc)
	}

	src = sb.String()
	// Remove unused send import if none of the params reference it.
	if !strings.Contains(src, "send.") {
		src = strings.Replace(src, "import (\n\t\"github.com/lenaxia/rathena-client/pkg/send\"\n)\n\n", "", 1)
	}

	return filename, src, nil
}

// resolveLayout finds the best available layout for a struct at a given packetver.
func resolveLayout(structName string, packetverMin int, vt preprocess.VersionTable) *preprocess.StructLayout {
	ranges, ok := vt[structName]
	if !ok || len(ranges) == 0 {
		return nil
	}
	pv := uint32(packetverMin)
	if pv == 0 {
		pv = 20030000
	}
	for i := len(ranges) - 1; i >= 0; i-- {
		r := ranges[i]
		if r.Layout != nil && r.Layout.Available && r.MinVer <= pv {
			return r.Layout
		}
	}
	for _, r := range ranges {
		if r.Layout != nil && r.Layout.Available {
			return r.Layout
		}
	}
	return nil
}

// hasFlexField reports whether any field in the layout is a C flexible array member
// (IsFlexArray=true). Such packets are variable-length: the struct body has a fixed
// header followed by a trailing variable payload. The encoder must return []byte and
// allocate based on the runtime payload length.
func hasFlexField(layout *preprocess.StructLayout) bool {
	for i := range layout.Fields {
		if layout.Fields[i].IsFlexArray {
			return true
		}
	}
	return false
}

// flexFieldGoName returns the exported Go identifier of the first IsFlexArray field
// in the layout, or "" if no flex field exists. Used to emit the dynamic allocation.
func flexFieldGoName(layout *preprocess.StructLayout) string {
	for i := range layout.Fields {
		if layout.Fields[i].IsFlexArray {
			return cFieldToGoIdent(layout.Fields[i].Name)
		}
	}
	return ""
}

// isLengthField reports whether the C field name represents the packet's own wire
// length. For structs with flex array payloads the encoder computes this value
// internally (as len(p) after allocation) rather than reading it from the caller.
func isLengthField(name string) bool {
	lower := strings.ToLower(name)
	return lower == "packetlength" || lower == "packetlen" || lower == "packetsize"
}

// generateEncodeFunc generates a single encode function for a packet implementation.
// Fields are derived directly from the rAthena struct layout — no canonical_params
// or field_mapping expressions needed.
//
// For fixed-size packets the function returns [N]byte (zero allocs).
// For variable-size packets (struct has a flex array field) it returns []byte and
// allocates dynamically based on the payload length.
func generateEncodeFunc(
	structName string,
	impl *semantics.Implementation,
	layout *preprocess.StructLayout,
) string {
	fnName := fmt.Sprintf("Encode%s", structName)
	totalSize := layout.TotalSize
	isVariable := totalSize <= 0 || hasFlexField(layout)

	returnType := fmt.Sprintf("[%d]byte", totalSize)
	if isVariable {
		returnType = "[]byte"
	}

	var sb strings.Builder
	sb.WriteString(fmt.Sprintf("// Encode%s encodes a %s (%s) packet for sending to the server.\n",
		structName, impl.PacketID, impl.StructName))
	sb.WriteString(fmt.Sprintf("func %s(req send.%s, packetver uint32) %s {\n", fnName, structName, returnType))

	if !isVariable {
		sb.WriteString(fmt.Sprintf("\tvar p %s\n", returnType))
	} else if flexName := flexFieldGoName(layout); flexName != "" {
		// Allocate header bytes + runtime length of the flex payload field.
		sb.WriteString(fmt.Sprintf("\tp := make([]byte, %d+len(req.%s))\n", totalSize, flexName))
	} else {
		sb.WriteString("\tp := make([]byte, 4)\n")
	}

	packetID := impl.PacketID
	sb.WriteString(fmt.Sprintf("\t// Packet ID: %s (little-endian)\n", packetID))
	sb.WriteString(fmt.Sprintf("\tp[0] = 0x%s\n", strings.ToLower(packetID[4:6])))
	sb.WriteString(fmt.Sprintf("\tp[1] = 0x%s\n", strings.ToLower(packetID[2:4])))

	for i := range layout.Fields {
		f := &layout.Fields[i]
		if f.Name == "PacketType" || f.Name == "packetType" || f.Name == "packet_type" {
			continue
		}
		// For variable-length packets the wire length is computed from len(p), not
		// taken from a caller-supplied field.  Emit the computation inline and skip
		// the req.PacketLength/PacketSize field (which is absent from the send struct
		// after send.go strips it for flex-array structs).
		if isVariable && isLengthField(f.Name) {
			sb.WriteString(fmt.Sprintf("\tleU16Put(p[%d:], uint16(len(p)))  // rAthena: %s (computed)\n", f.Offset, f.Name))
			continue
		}
		goFieldName := cFieldToGoIdent(f.Name)
		goType := cTypeToGoType(f)
		writeStmt := fieldWriteStmt("p", f, goType, fmt.Sprintf("req.%s", goFieldName))
		sb.WriteString(writeStmt)
	}

	sb.WriteString("\t_ = packetver\n")
	sb.WriteString("\treturn p\n}\n")
	return sb.String()
}

// generateEncodeDispatcher generates a multi-version encode dispatcher.
// Returns an error string (non-empty) if no implementations can be resolved.
func generateEncodeDispatcher(
	structName string,
	a *semantics.Action,
	vt preprocess.VersionTable,
) string {
	var sb strings.Builder

	impls := make([]semantics.Implementation, len(a.Implementations))
	copy(impls, a.Implementations)
	sort.Slice(impls, func(i, j int) bool {
		return impls[i].PacketverMin < impls[j].PacketverMin
	})

	// Caller has already filtered to send-direction; the internal filter here is
	// kept as a safety net in case generateEncodeDispatcher is called directly.
	sendImpls := make([]semantics.Implementation, 0, len(impls))
	for _, impl := range impls {
		if isSendStruct(impl.StructName) {
			sendImpls = append(sendImpls, impl)
		}
	}
	impls = sendImpls

	// Determine the common fixed size across all resolvable implementations.
	// Any flex-array field forces the whole dispatcher to return []byte.
	commonSize := -1
	for i := range impls {
		layout := resolveLayout(impls[i].StructName, impls[i].PacketverMin, vt)
		if layout == nil {
			continue
		}
		if layout.TotalSize <= 0 || hasFlexField(layout) {
			commonSize = 0
			break
		}
		if commonSize == -1 {
			commonSize = layout.TotalSize
		} else if commonSize != layout.TotalSize {
			commonSize = 0
			break
		}
	}

	var returnType string
	if commonSize > 0 {
		returnType = fmt.Sprintf("[%d]byte", commonSize)
	} else {
		returnType = "[]byte"
	}

	sb.WriteString(fmt.Sprintf("// Encode%s encodes a %s packet for the appropriate packet version.\n", structName, structName))
	sb.WriteString(fmt.Sprintf("func Encode%s(req send.%s, packetver uint32) %s {\n", structName, structName, returnType))
	sb.WriteString("\tswitch {\n")

	for i := len(impls) - 1; i >= 0; i-- {
		impl := &impls[i]
		layout := resolveLayout(impl.StructName, impl.PacketverMin, vt)
		if layout == nil {
			continue
		}
		sb.WriteString(fmt.Sprintf("\tcase packetver >= %d: // %s\n", impl.PacketverMin, impl.PacketID))
		totalSize := layout.TotalSize
		isImplVariable := totalSize <= 0 || hasFlexField(layout)
		if commonSize > 0 {
			sb.WriteString(fmt.Sprintf("\t\tvar p [%d]byte\n", commonSize))
		} else if !isImplVariable {
			sb.WriteString(fmt.Sprintf("\t\tp := make([]byte, %d)\n", totalSize))
		} else if flexName := flexFieldGoName(layout); flexName != "" {
			sb.WriteString(fmt.Sprintf("\t\tp := make([]byte, %d+len(req.%s))\n", totalSize, flexName))
		} else {
			sb.WriteString("\t\tp := make([]byte, 4)\n")
		}
		packetID := impl.PacketID
		sb.WriteString(fmt.Sprintf("\t\tp[0] = 0x%s; p[1] = 0x%s\n",
			strings.ToLower(packetID[4:6]),
			strings.ToLower(packetID[2:4])))

		for j := range layout.Fields {
			f := &layout.Fields[j]
			if f.Name == "PacketType" || f.Name == "packetType" || f.Name == "packet_type" {
				continue
			}
			if isImplVariable && isLengthField(f.Name) {
				sb.WriteString(fmt.Sprintf("\t\tleU16Put(p[%d:], uint16(len(p)))  // rAthena: %s (computed)\n", f.Offset, f.Name))
				continue
			}
			goFieldName := cFieldToGoIdent(f.Name)
			goType := cTypeToGoType(f)
			writeStmt := fieldWriteStmt("\t\tp", f, goType, fmt.Sprintf("req.%s", goFieldName))
			sb.WriteString(writeStmt)
		}
		sb.WriteString("\t\treturn p\n")
	}
	sb.WriteString("\t}\n")
	sb.WriteString("\tpanic(\"Encode" + structName + ": no matching packetver implementation — unimplemented\")\n}\n")
	return sb.String()
}

// fieldWriteStmt emits a statement that writes a value into a byte slice p at field offset.
func fieldWriteStmt(pVar string, f *preprocess.Field, goType, reqExpr string) string {
	off := f.Offset
	switch goType {
	case "uint8":
		return fmt.Sprintf("\t%s[%d] = %s  // rAthena: %s\n", pVar, off, reqExpr, f.Name)
	case "int8":
		return fmt.Sprintf("\t%s[%d] = uint8(%s)  // rAthena: %s\n", pVar, off, reqExpr, f.Name)
	case "uint16":
		return fmt.Sprintf("\tleU16Put(%s[%d:], %s)  // rAthena: %s\n", pVar, off, reqExpr, f.Name)
	case "int16":
		return fmt.Sprintf("\tleU16Put(%s[%d:], uint16(%s))  // rAthena: %s\n", pVar, off, reqExpr, f.Name)
	case "uint32":
		return fmt.Sprintf("\tleU32Put(%s[%d:], %s)  // rAthena: %s\n", pVar, off, reqExpr, f.Name)
	case "int32":
		return fmt.Sprintf("\tleU32Put(%s[%d:], uint32(%s))  // rAthena: %s\n", pVar, off, reqExpr, f.Name)
	case "string":
		if f.IsFlexArray {
			// Flex char[] field: open-ended copy into the already-allocated buffer.
			return fmt.Sprintf("\tcopy(%s[%d:], %s)  // rAthena: %s\n", pVar, off, reqExpr, f.Name)
		}
		if f.IsArray {
			return fmt.Sprintf("\tcopy(%s[%d:%d], %s)  // rAthena: %s\n", pVar, off, off+f.Size, reqExpr, f.Name)
		}
		return fmt.Sprintf("\tcopy(%s[%d:], %s)  // rAthena: %s\n", pVar, off, reqExpr, f.Name)
	case "[]byte":
		return fmt.Sprintf("\tcopy(%s[%d:], %s)  // rAthena: %s\n", pVar, off, reqExpr, f.Name)
	default:
		if strings.HasPrefix(goType, "[") {
			return fmt.Sprintf("\tcopy(%s[%d:], %s[:])  // rAthena: %s\n", pVar, off, reqExpr, f.Name)
		}
		return fmt.Sprintf("\t// %s: unhandled type %s for rAthena: %s\n", reqExpr, goType, f.Name)
	}
}

// GenerateEncodeDirFiles generates all encode files from a semantics DB + VersionTable.
func GenerateEncodeDirFiles(db *semantics.DB, vt preprocess.VersionTable) (map[string]string, []string, error) {
	if db == nil {
		return nil, nil, fmt.Errorf("nil DB")
	}

	// fsmOwnedActions are semantic actions whose packets cannot be generated by
	// the codegen pipeline because their struct layouts are unknown or unverified.
	// Entries should be removed as their layouts are confirmed and added to
	// synthetic_structs.hpp or common/packets.hpp.
	//
	// NOTE: 0x0275 (SYNTH_CH_ENTER) has UNAVAILABLE_STRUCT — its layout beyond the
	// 2-byte packetType is unknown and must not be emitted by codegen. The game_login
	// action's 0x0065 impl uses SYNTH_CH_ENTER_0x0065 (confirmed layout), but the
	// 0x0275 impl (SYNTH_CH_ENTER) has no resolvable layout, so GenerateEncodeFile
	// will skip it gracefully — no entry needed here.
	fsmOwnedActions := map[string]bool{}

	result := make(map[string]string)
	var skipped []string

	names := make([]string, 0, len(db.Actions))
	for name := range db.Actions {
		names = append(names, name)
	}
	sort.Strings(names)

	for _, name := range names {
		action := db.Actions[name]
		if len(action.Implementations) == 0 {
			continue
		}

		// Skip actions that are owned by pkg/fsm and built there directly.
		if fsmOwnedActions[name] {
			skipped = append(skipped, fmt.Sprintf("%s: fsm-owned, skipped", name))
			continue
		}

		// Only encode C→S packets.
		isSend := false
		for _, impl := range action.Implementations {
			if isSendStruct(impl.StructName) {
				isSend = true
				break
			}
		}
		if !isSend {
			continue
		}

		filename, src, err := GenerateEncodeFile(EncodeInput{
			Action:       action,
			VersionTable: vt,
		})
		if err != nil {
			skipped = append(skipped, fmt.Sprintf("%s: %v", name, err))
			continue
		}

		result[filename] = src
	}

	return result, skipped, nil
}
