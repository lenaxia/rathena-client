func TestGenerateLengthsFile_Basic(t *testing.T) {
	breakpoints := []gen.LengthBreakpoint{
		{
			Ver: 0, // baseline (always active)
			Entries: []gen.LengthEntry{
				{ID: 0x0064, Length: 55},
				{ID: 0x0069, Length: -1},
			},
		},
		{
			Ver: 20170315,
			Entries: []gen.LengthEntry{
				{ID: 0x0AC4, Length: -1},
			},
		},
	}

	src, err := gen.GenerateLengthsFile(gen.ServerLogin, breakpoints)
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}

	// Verify the generated code contains expected elements.
	checks := []string{
		"package session",
		"func populateLoginLengths(pv uint32, t *[65536]int16)",
		"t[0x0064] = 55",
		"t[0x0069] = -1",
		"if pv >= 20170315",
		"t[0x0AC4] = -1",
		"// Code generated by internal/codegen. DO NOT EDIT.",
	}
	for _, want := range checks {
		if !strings.Contains(src, want) {
			t.Errorf("generated source missing %q", want)
		}
	}
}

func TestGenerateLengthsFile_ServerTypes(t *testing.T) {
	bp := []gen.LengthBreakpoint{{Ver: 0, Entries: []gen.LengthEntry{{ID: 0x0064, Length: 4}}}}
	for _, server := range []gen.ServerType{gen.ServerLogin, gen.ServerChar, gen.ServerMap} {
		src, err := gen.GenerateLengthsFile(server, bp)
		if err != nil {
			t.Fatalf("%s: unexpected error: %v", server, err)
		}
		want := "func populate" + strings.ToUpper(string(server[:1])) + string(server[1:]) + "Lengths"
		if !strings.Contains(src, want) {
			t.Errorf("%s: missing %q in:\n%s", server, want, src)
		}
	}
}

