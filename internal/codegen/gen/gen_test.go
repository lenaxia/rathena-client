func TestGenerateActionsFile_AlphabeticalOrder(t *testing.T) {
	db := &semantics.DB{
		Actions: map[string]*semantics.Action{
			"zoo_event":   {Name: "zoo_event"},
			"apple_event": {Name: "apple_event"},
			"mango_event": {Name: "mango_event"},
		},
	}

	src, err := gen.GenerateActionsFile(db)
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}

	applePos := strings.Index(src, "ActionAppleEvent")
	mangoPos := strings.Index(src, "ActionMangoEvent")
	zooPos := strings.Index(src, "ActionZooEvent")

	if applePos == -1 || mangoPos == -1 || zooPos == -1 {
		t.Fatalf("one or more constants not found in generated source:\n%s", src)
	}
	if !(applePos < mangoPos && mangoPos < zooPos) {
		t.Errorf("constants not in alphabetical order: apple=%d mango=%d zoo=%d", applePos, mangoPos, zooPos)
	}

	if !strings.Contains(src, "ActionUnknown SemanticAction = 0") {
		t.Error("ActionUnknown = 0 not found")
	}
	if !strings.Contains(src, "ActionAppleEvent SemanticAction = 1") {
		t.Error("ActionAppleEvent should be = 1 (first alphabetically)")
	}
}

