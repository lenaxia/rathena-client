package gen

import (
	"fmt"
	"sort"
	"strings"

	"github.com/lenaxia/rathena-client/internal/codegen/preprocess"
	"github.com/lenaxia/rathena-client/internal/codegen/semantics"
)

// GenerateReceiveDispatchFile generates the Go source for
// pkg/session/receive_dispatch.go.
//
// The file contains a receiveDispatch map from SemanticAction to []receiveEntry,
// covering all receive-direction implementations across all semantic actions.
// Direction is determined per-implementation via isReceiveStruct(impl.StructName).
//
// When vt is non-nil, implementations whose struct is absent from the VersionTable
// are silently skipped — they have no corresponding generated decode function.
// Pass a nil VersionTable to include all receive-direction implementations regardless
// of whether a decode function was generated (used in unit tests).
func GenerateReceiveDispatchFile(db *semantics.DB, vt preprocess.VersionTable) (string, error) {
	if db == nil {
		return "", fmt.Errorf("nil DB")
	}

	names := make([]string, 0, len(db.Actions))
	for name := range db.Actions {
		names = append(names, name)
	}
	sort.Strings(names)

	// First pass: collect per-action entries and determine which actions are skipped.
	type entryLine struct {
		packetID string
		funcName string
	}
	type actionEntries struct {
		name    string
		entries []entryLine
	}

	var included []actionEntries
	var skippedNames []string

	for _, name := range names {
		action := db.Actions[name]
		goIdent := actionNameToGoIdent(name)

		var entries []entryLine
		for _, impl := range action.Implementations {
			if impl.PacketID == "" || impl.StructName == "" {
				continue
			}
			if !isReceiveStruct(impl.StructName) {
				continue
			}
			// When a VersionTable is provided, skip structs absent from it —
			// those have no generated decode function (e.g. Zero-client-only packets).
			if len(vt) > 0 {
				if _, ok := vt[impl.StructName]; !ok {
					continue
				}
			}
			funcName := fmt.Sprintf("decode.%s_%s", goIdent, impl.PacketID)
			entries = append(entries, entryLine{
				packetID: impl.PacketID,
				funcName: funcName,
			})
		}

		if len(entries) == 0 {
			skippedNames = append(skippedNames, name)
		} else {
			included = append(included, actionEntries{name: name, entries: entries})
		}
	}

	var sb strings.Builder
	sb.WriteString("// Code generated by internal/codegen. DO NOT EDIT.\n\n")
	sb.WriteString("package session\n\n")
	sb.WriteString("import (\n")
	sb.WriteString("\t\"github.com/lenaxia/rathena-client/pkg/decode\"\n")
	sb.WriteString(")\n\n")

	// Emit omitted actions as a comment block before the map.
	if len(skippedNames) > 0 {
		sb.WriteString("// The following actions have no receive-direction implementations\n")
		sb.WriteString("// (all implementations are send-direction or have empty PacketID/StructName)\n")
		sb.WriteString("// and are therefore absent from receiveDispatch:\n")
		for _, name := range skippedNames {
			sb.WriteString(fmt.Sprintf("//   %s\n", name))
		}
		sb.WriteString("\n")
	}

	sb.WriteString("// receiveEntry holds one packet-ID → decode-function mapping for a semantic action.\n")
	sb.WriteString("type receiveEntry struct {\n")
	sb.WriteString("\tid uint16\n")
	sb.WriteString("\tfn func([]byte, uint32) interface{}\n")
	sb.WriteString("}\n\n")

	sb.WriteString("// receiveDispatch maps each receive-direction SemanticAction to its full set of\n")
	sb.WriteString("// packet IDs and decode functions across all packetver variants.\n")
	sb.WriteString("var receiveDispatch = map[SemanticAction][]receiveEntry{\n")

	for _, ae := range included {
		goIdent := actionNameToGoIdent(ae.name)
		sb.WriteString(fmt.Sprintf("\tAction%s: {\n", goIdent))
		for _, e := range ae.entries {
			sb.WriteString(fmt.Sprintf("\t\t{id: %s, fn: func(d []byte, pv uint32) interface{} { return %s(d, pv) }},\n",
				e.packetID, e.funcName))
		}
		sb.WriteString("\t},\n")
	}

	sb.WriteString("}\n")

	return sb.String(), nil
}
