package gen

import (
	"fmt"
	"sort"
	"strings"
)

// ObfuscationKeySet holds the three LCG keys for a specific PACKETVER.
type ObfuscationKeySet struct {
	PacketVer uint32
	Key0      uint32
	Key1      uint32
	Key2      uint32
}

// GenerateObfuscationFile generates the Go source for pkg/session/obfuscation_keys.go.
// It produces `ObfuscationKeysFor(packetver uint32) (k0, k1, k2 uint32)` that
// returns the three keys for packet ID obfuscation. Returns (0,0,0) for
// PACKETVER > 20180307 (obfuscation discontinued).
func GenerateObfuscationFile(keys []ObfuscationKeySet) (string, error) {
	// Sort by PacketVer ascending.
	sorted := make([]ObfuscationKeySet, len(keys))
	copy(sorted, keys)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].PacketVer < sorted[j].PacketVer })

	var sb strings.Builder
	sb.WriteString("// Code generated by internal/codegen. DO NOT EDIT.\n\n")
	sb.WriteString("package session\n\n")
	sb.WriteString("// ObfuscationKeysFor returns the three C→S packet-ID obfuscation keys for\n")
	sb.WriteString("// the given packetver. Returns (0, 0, 0) for packetver > 20180307\n")
	sb.WriteString("// (obfuscation discontinued) or any packetver not in the key table.\n")
	sb.WriteString("// Callers: if k0|k1|k2 != 0 { session.EnableObfuscation(k0, k1, k2) }\n")
	sb.WriteString("//\n")
	sb.WriteString("// Source: src/map/clif_obfuscation.hpp (preprocessed with -DPACKET_OBFUSCATION)\n")
	sb.WriteString("func ObfuscationKeysFor(packetver uint32) (k0, k1, k2 uint32) {\n")

	if len(sorted) == 0 {
		sb.WriteString("\treturn 0, 0, 0\n}\n")
		return sb.String(), nil
	}

	sb.WriteString("\tswitch packetver {\n")
	for _, k := range sorted {
		sb.WriteString(fmt.Sprintf("\tcase %d:\n", k.PacketVer))
		sb.WriteString(fmt.Sprintf("\t\treturn 0x%08X, 0x%08X, 0x%08X\n", k.Key0, k.Key1, k.Key2))
	}
	sb.WriteString("\t}\n")
	sb.WriteString("\treturn 0, 0, 0\n}\n")
	return sb.String(), nil
}
