package gen

import (
	"fmt"
	"sort"
	"strings"

	"github.com/lenaxia/rathena-client/internal/codegen/preprocess"
)

// ShuffleEntry maps a base C→S packet ID to its shuffled ID at a specific PACKETVER.
type ShuffleEntry struct {
	BaseID    uint16 // the canonical (unshuffled) packet ID
	ShuffleID uint16 // the wire packet ID at this exact PACKETVER
}

// ShuffleBreakpoint is a PACKETVER == N block from clif_shuffle.hpp.
type ShuffleBreakpoint struct {
	Ver     uint32
	Entries []ShuffleEntry
}

// BuildShuffleBreakpoints converts parsed ShuffleSections and the base ID map
// into ShuffleBreakpoints. The baseIDs map maps handler names → base packet IDs
// (from HandlerBaseIDs(ParsePacketDB(...))).
func BuildShuffleBreakpoints(sections []preprocess.ShuffleSection, baseIDs map[string]preprocess.PacketEntry) []ShuffleBreakpoint {
	var bps []ShuffleBreakpoint
	for _, sec := range sections {
		var entries []ShuffleEntry
		seen := make(map[uint16]bool) // deduplicate within a section
		for _, e := range sec.Entries {
			if e.Handler == "" {
				continue
			}
			base, ok := baseIDs[e.Handler]
			if !ok {
				continue
			}
			if base.ID == e.ID {
				continue // no shuffle needed — same ID
			}
			if seen[base.ID] {
				continue // already recorded a shuffle for this base ID in this section
			}
			seen[base.ID] = true
			entries = append(entries, ShuffleEntry{
				BaseID:    base.ID,
				ShuffleID: e.ID,
			})
		}
		if len(entries) > 0 {
			bps = append(bps, ShuffleBreakpoint{
				Ver:     sec.PacketVer,
				Entries: entries,
			})
		}
	}
	return bps
}

// GenerateShuffleFile generates the Go source for pkg/session/shuffle_map.go.
// It produces `ShuffledCtoSID(packetver uint32, baseID uint16) uint16` that
// returns the shuffled C→S wire packet ID for a given base packet ID at the
// given packetver. Returns baseID unchanged if no shuffle exists for this packetver.
func GenerateShuffleFile(breakpoints []ShuffleBreakpoint) (string, error) {
	// Sort by Ver ascending.
	sorted := make([]ShuffleBreakpoint, len(breakpoints))
	copy(sorted, breakpoints)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Ver < sorted[j].Ver })

	var sb strings.Builder
	sb.WriteString("// Code generated by internal/codegen. DO NOT EDIT.\n\n")
	sb.WriteString("package session\n\n")
	sb.WriteString("// ShuffledCtoSID returns the shuffled C→S wire packet ID for a given base packet ID\n")
	sb.WriteString("// at the given packetver. Returns baseID unchanged if no shuffle exists for this\n")
	sb.WriteString("// packetver (i.e. packetver is not one of the exact PACKETVER == values in\n")
	sb.WriteString("// src/map/clif_shuffle.hpp).\n")
	sb.WriteString("//\n")
	sb.WriteString("// Source: src/map/clif_shuffle.hpp\n")
	sb.WriteString("func ShuffledCtoSID(packetver uint32, baseID uint16) uint16 {\n")

	if len(sorted) == 0 {
		sb.WriteString("\treturn baseID\n}\n")
		return sb.String(), nil
	}

	sb.WriteString("\tswitch packetver {\n")
	for _, bp := range sorted {
		if len(bp.Entries) == 0 {
			continue
		}
		// Sort entries by BaseID for deterministic output.
		sortedEntries := make([]ShuffleEntry, len(bp.Entries))
		copy(sortedEntries, bp.Entries)
		sort.Slice(sortedEntries, func(i, j int) bool { return sortedEntries[i].BaseID < sortedEntries[j].BaseID })

		sb.WriteString(fmt.Sprintf("\tcase %d:\n", bp.Ver))
		sb.WriteString("\t\tswitch baseID {\n")
		for _, e := range sortedEntries {
			sb.WriteString(fmt.Sprintf("\t\tcase 0x%04X:\n\t\t\treturn 0x%04X\n", e.BaseID, e.ShuffleID))
		}
		sb.WriteString("\t\t}\n")
	}
	sb.WriteString("\t}\n")
	sb.WriteString("\treturn baseID\n}\n")
	return sb.String(), nil
}
