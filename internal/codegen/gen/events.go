package gen

import (
	"fmt"
	"sort"
	"strings"
	"unicode"

	"github.com/lenaxia/rathena-client/internal/codegen/semantics"
)

// EventsInput describes a single semantic action to generate an event struct for.
type EventsInput struct {
	Action *semantics.Action
}

// GenerateEventsFile generates the Go source for pkg/events/<action_name>.go.
//
// Each file contains a single exported struct whose fields are derived from the
// action's canonical_params. Field types are normalised from the (potentially
// invalid) DB types to valid Go types.
//
// The generated package is "events". Field names are exported (PascalCase).
func GenerateEventsFile(input EventsInput) (filename string, src string, err error) {
	a := input.Action
	if a == nil {
		return "", "", fmt.Errorf("nil action")
	}
	if a.Name == "" {
		return "", "", fmt.Errorf("action has empty name")
	}

	structName := actionNameToGoIdent(a.Name)
	filename = actionNameToFilename(a.Name)

	var sb strings.Builder
	sb.WriteString("// Code generated by internal/codegen. DO NOT EDIT.\n\n")
	sb.WriteString("package events\n\n")

	if a.Description != "" {
		sb.WriteString(fmt.Sprintf("// %s is the event emitted when a %s packet is received.\n", structName, a.Name))
		// Wrap long description lines.
		desc := a.Description
		if len(desc) > 80 {
			sb.WriteString(fmt.Sprintf("// %s\n", desc))
		} else {
			sb.WriteString(fmt.Sprintf("// %s\n", desc))
		}
	}
	sb.WriteString(fmt.Sprintf("type %s struct {\n", structName))

	for _, p := range a.CanonicalParams {
		if p.Name == "" {
			continue
		}
		fieldName := paramNameToGoIdent(p.Name)
		goType := normaliseGoType(p.Type)
		comment := ""
		if goType == "[6]byte" {
			comment = " // Packed movement data (6 bytes: from_x, from_y, to_x, to_y, sx0, sy0). Call packing.DecodeMoveData to unpack."
		} else if p.Semantic != "" {
			comment = " // " + fixScalarNilComment(sanitiseComment(p.Semantic), goType)
		}
		sb.WriteString(fmt.Sprintf("\t%s %s%s\n", fieldName, goType, comment))
	}

	sb.WriteString("}\n")

	return filename, sb.String(), nil
}

// GenerateEventsDirFiles generates all event files from a semantics DB.
// Returns a map of filename → Go source string.
func GenerateEventsDirFiles(db *semantics.DB) (map[string]string, error) {
	if db == nil {
		return nil, fmt.Errorf("nil DB")
	}

	result := make(map[string]string, len(db.Actions))

	// Sort action names for deterministic output.
	names := make([]string, 0, len(db.Actions))
	for name := range db.Actions {
		names = append(names, name)
	}
	sort.Strings(names)

	for _, name := range names {
		action := db.Actions[name]
		if len(action.CanonicalParams) == 0 {
			// No params — skip (no useful struct to generate).
			continue
		}
		filename, src, err := GenerateEventsFile(EventsInput{Action: action})
		if err != nil {
			return nil, fmt.Errorf("action %s: %w", name, err)
		}
		result[filename] = src
	}

	return result, nil
}

// actionNameToGoIdent converts a snake_case action name to a Go PascalCase identifier.
// e.g. "actor_exists" → "ActorExists"
func actionNameToGoIdent(name string) string {
	parts := strings.Split(name, "_")
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	return b.String()
}

// actionNameToFilename converts an action name to a Go source filename.
// e.g. "actor_exists" → "actor_exists.go"
// The name is lowercased to avoid case-insensitive filesystem collisions.
func actionNameToFilename(name string) string {
	return strings.ToLower(name) + ".go"
}

// paramNameToGoIdent converts a param name to an exported Go identifier.
// Both snake_case and Mixed_case names are converted to PascalCase.
func paramNameToGoIdent(name string) string {
	// Always apply snake_case → PascalCase conversion to handle names like
	// "Clothes_color" (starts uppercase but contains underscores).
	if strings.Contains(name, "_") {
		return actionNameToGoIdent(name)
	}
	// If the name already starts with uppercase and has no underscores, treat as PascalCase.
	if len(name) > 0 && unicode.IsUpper(rune(name[0])) {
		return name
	}
	// snake_case → PascalCase.
	return actionNameToGoIdent(name)
}

// normaliseGoType converts a DB type string (which may contain C-style or
// invalid Go types) into a valid Go type string.
func normaliseGoType(t string) string {
	t = strings.TrimSpace(t)
	switch t {
	case "uint8", "uint16", "uint32", "uint64",
		"int8", "int16", "int32", "int64",
		"bool", "string", "[]byte",
		"[]int16", "[]uint16", "[]uint32":
		return t
	case "char":
		return "uint8"
	case "char[NAME_LENGTH]", "char[20]":
		return "string"
	case "*uint8":
		return "uint8"
	case "*uint16":
		return "uint16"
	case "*uint32":
		return "uint32"
	case "*string":
		return "string"
	case "[3]byte", "[6]byte",
		"[4]byte", "[16]byte", "[24]byte", "[40]byte":
		return t
	case "[3]uint8":
		return "[3]uint8"
	case "[4]uint32", "[10]uint32":
		return t
	case "[5]ItemOptions":
		return "[]byte" // complex nested type, use raw bytes
	case "struct EQUIPSLOTINFO":
		return "[]byte" // complex nested type, use raw bytes
	default:
		// Arrays like "char[N]" → string.
		if strings.HasPrefix(t, "char[") {
			return "string"
		}
		// Pointer types like "*SomeType" → drop the pointer.
		if strings.HasPrefix(t, "*") {
			inner := normaliseGoType(t[1:])
			return inner
		}
		// Unknown type — fall back to []byte.
		return "[]byte"
	}
}

// sanitiseComment strips newlines and trims the comment to a reasonable length.
func sanitiseComment(s string) string {
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.ReplaceAll(s, "\r", "")
	if len(s) > 120 {
		s = s[:117] + "..."
	}
	return s
}

// fixScalarNilComment replaces "may be nil" language in comments for scalar Go types
// (uint8/uint16/uint32/uint64/int8/int16/int32/int64) with "zero if absent", since
// scalar types in Go cannot be nil.
func fixScalarNilComment(comment, goType string) string {
	scalarTypes := map[string]bool{
		"uint8": true, "uint16": true, "uint32": true, "uint64": true,
		"int8": true, "int16": true, "int32": true, "int64": true,
		"bool": true,
	}
	if !scalarTypes[goType] {
		return comment
	}
	comment = strings.ReplaceAll(comment, "may be nil", "zero if absent")
	return comment
}
