// EventsInput describes a single semantic action to generate an event struct for.
type EventsInput struct {
	Action       *semantics.Action
	VersionTable preprocess.VersionTable
}

// GenerateEventsFile generates the Go source for pkg/events/<action_name>.go.
//
// The event struct fields are derived directly from the rAthena struct layout of
// the action's first receive-direction implementation. Field names use the rAthena
// C field names (capitalised to exported Go identifiers). Field types are derived
// from the C types.
//
// Fields from all implementations of the same action are merged: the union of
// fields across all struct versions becomes the event struct. Fields present in
// some versions but not others are still included (they will be zero-valued when
// absent).
func GenerateEventsFile(input EventsInput) (filename string, src string, err error) {
	a := input.Action
	if a == nil {
		return "", "", fmt.Errorf("nil action")
	}
	if a.Name == "" {
		return "", "", fmt.Errorf("action has empty name")
	}

	structName := actionNameToGoIdent(a.Name)
	filename = actionNameToFilename(a.Name)

	// Collect the union of fields across all receive-direction implementations.
	// Use the first implementation's representative layout for field ordering.
	fields, err := mergedEventFields(a, input.VersionTable)
	if err != nil || len(fields) == 0 {
		// No fields derivable — emit an empty struct with a comment.
		src = fmt.Sprintf("// Code generated by internal/codegen. DO NOT EDIT.\n\npackage events\n\n// %s is the event emitted for the %s action.\ntype %s struct{}\n",
			structName, a.Name, structName)
		return filename, src, nil
	}

	var sb strings.Builder
	sb.WriteString("// Code generated by internal/codegen. DO NOT EDIT.\n\n")
	sb.WriteString("package events\n\n")
	sb.WriteString(fmt.Sprintf("// %s is the event emitted for the %s action.\n", structName, a.Name))
	sb.WriteString(fmt.Sprintf("type %s struct {\n", structName))

	for _, ef := range fields {
		comment := ""
		if ef.GoType == "[6]byte" {
			comment = " // Packed movement data (6 bytes: from_x, from_y, to_x, to_y, sx0, sy0). Call packing.DecodeMoveData to unpack."
		}
		sb.WriteString(fmt.Sprintf("\t%s %s%s\n", ef.GoName, ef.GoType, comment))
	}

	sb.WriteString("}\n")
	return filename, sb.String(), nil
}

// eventField is a field entry in the merged event struct.
type eventField struct {
	GoName string
	GoType string
}

// mergedEventFields collects the union of exported fields across all receive-direction
// implementations and all their layout versions. When the same field name appears with
// different types across versions, the wider/later type wins.
// Fields named PacketType/packetType are excluded.
func mergedEventFields(a *semantics.Action, vt preprocess.VersionTable) ([]eventField, error) {
	// Track field name → type; preserve insertion order via slice.
	seen := make(map[string]string)
	var ordered []eventField

	for _, impl := range a.Implementations {
		if impl.StructName == "" {
			continue
		}
		if !isReceiveStruct(impl.StructName) {
			continue
		}

		// Collect from ALL version ranges for this struct, not just one.
		ranges, ok := vt[impl.StructName]
		if !ok {
			continue
		}
		for _, vr := range ranges {
			if vr.Layout == nil || !vr.Layout.Available {
				continue
			}
			for i := range vr.Layout.Fields {
				f := &vr.Layout.Fields[i]
				if f.Name == "PacketType" || f.Name == "packetType" || f.Name == "packet_type" {
					continue
				}
				goName := cFieldToGoIdent(f.Name)
				goType := cTypeToGoType(f)
				if existingType, exists := seen[goName]; !exists {
					seen[goName] = goType
					ordered = append(ordered, eventField{GoName: goName, GoType: goType})
				} else if existingType != goType {
					// Type conflict across versions — use the wider type.
					wider := widenType(existingType, goType)
					if wider != existingType {
						// Update the type in-place.
						seen[goName] = wider
						for j := range ordered {
							if ordered[j].GoName == goName {
								ordered[j].GoType = wider
								break
							}
						}
					}
				}
			}
		}
	}

	return ordered, nil
}

// widenType returns the wider of two Go numeric types.
// When a field changes type across PACKETVER (e.g. int16 → int32), the event
// struct must use the wider type to accommodate all decode branches.
func widenType(a, b string) string {
	order := []string{
		"uint8", "int8",
		"uint16", "int16",
		"uint32", "int32",
		"uint64", "int64",
	}
	ai, bi := -1, -1
	for i, t := range order {
		if t == a {
			ai = i
		}
		if t == b {
			bi = i
		}
	}
	// If either is not a scalar, keep the existing type.
	if ai < 0 || bi < 0 {
		return a
	}
	// Return the type with the higher index (wider).
	if bi > ai {
		return b
	}
	return a
}

// isReceiveStruct returns true for server→client structs.
func isReceiveStruct(structName string) bool {
	upper := strings.ToUpper(structName)
	for _, prefix := range []string{
		"PACKET_ZC_", "PACKET_HC_", "PACKET_AC_", "PACKET_SC_", "PACKET_TC_",
		"SYNTH_ZC_", "SYNTH_HC_",
	} {
		if strings.HasPrefix(upper, prefix) {
			return true
		}
	}
	return strings.HasPrefix(structName, "packet_")
}

// GenerateEventsDirFiles generates all event files from a semantics DB + VersionTable.
// Returns a map of filename → Go source string.
func GenerateEventsDirFiles(db *semantics.DB, vt preprocess.VersionTable) (map[string]string, error) {
	if db == nil {
		return nil, fmt.Errorf("nil DB")
	}

	result := make(map[string]string, len(db.Actions))

	names := make([]string, 0, len(db.Actions))
	for name := range db.Actions {
		names = append(names, name)
	}
	sort.Strings(names)

	for _, name := range names {
		action := db.Actions[name]

		// Only generate event types for receive (S→C) actions.
		hasReceive := false
		for _, impl := range action.Implementations {
			if isReceiveStruct(impl.StructName) {
				hasReceive = true
				break
			}
		}
		if !hasReceive {
			continue
		}

		filename, src, err := GenerateEventsFile(EventsInput{Action: action, VersionTable: vt})
		if err != nil {
			return nil, fmt.Errorf("action %s: %w", name, err)
		}
		result[filename] = src
	}

	return result, nil
}

// actionNameToGoIdent converts a snake_case action name to a Go PascalCase identifier.
// e.g. "actor_exists" → "ActorExists"
func actionNameToGoIdent(name string) string {
	parts := strings.Split(name, "_")
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	return b.String()
}

// actionNameToFilename converts an action name to a Go source filename.
func actionNameToFilename(name string) string {
	return strings.ToLower(name) + ".go"
}

// paramNameToGoIdent is kept for compatibility — delegates to cFieldToGoIdent.
func paramNameToGoIdent(name string) string {
	return cFieldToGoIdent(name)
}

// normaliseGoType is kept for compatibility with encode.go.
// In the new model, types are derived via cTypeToGoType; this is a fallback
// for any callers that still pass raw DB type strings.
func normaliseGoType(t string) string {
	t = strings.TrimSpace(t)
	switch t {
	case "uint8", "uint16", "uint32", "uint64",
		"int8", "int16", "int32", "int64",
		"bool", "string", "[]byte",
		"[]int16", "[]uint16", "[]uint32":
		return t
	case "char":
		return "uint8"
	case "[3]byte", "[6]byte", "[4]byte", "[16]byte", "[24]byte", "[40]byte":
		return t
	default:
		if strings.HasPrefix(t, "char[") {
			return "string"
		}
		if strings.HasPrefix(t, "[") {
			return t
		}
		return "[]byte"
	}
}

// sanitiseComment strips newlines and trims the comment to a reasonable length.
func sanitiseComment(s string) string {
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.ReplaceAll(s, "\r", "")
	if len(s) > 120 {
		s = s[:117] + "..."
	}
	return s
}

// fixScalarNilComment is kept for compatibility.
func fixScalarNilComment(comment, goType string) string {
	scalarTypes := map[string]bool{
		"uint8": true, "uint16": true, "uint32": true, "uint64": true,
		"int8": true, "int16": true, "int32": true, "int64": true,
		"bool": true,
	}
	if !scalarTypes[goType] {
		return comment
	}
	comment = strings.ReplaceAll(comment, "may be nil", "zero if absent")
	return comment
}
