package gen

import (
	"fmt"
	"sort"
	"strings"
)

// LengthEntry maps a packet ID to its length at a specific PACKETVER.
// Length -1 means variable-length (the frame's bytes [2:4] hold the total length).
// Length 0 means unknown (will cause Feed() to return ErrUnknownPacket).
type LengthEntry struct {
	ID     uint16
	Length int16
}

// LengthBreakpoint is a PACKETVER at which one or more packet lengths change.
// All IDs listed are (re)assigned the given Length starting at this PACKETVER.
type LengthBreakpoint struct {
	Ver     uint32
	Entries []LengthEntry
}

// ServerType identifies which server's length table is being generated.
type ServerType string

const (
	ServerLogin ServerType = "login"
	ServerChar  ServerType = "char"
	ServerMap   ServerType = "map"
)

// GenerateLengthsFile generates the Go source for a lengths_*.go file.
// It produces a function `populateLengths(pv uint32, t *[65536]int16)` that
// initialises the session length table for the given PACKETVER.
//
// breakpoints must be sorted ascending by Ver. Each entry contains the set of
// packet ID→length assignments that become active at that PACKETVER.
// The generated function applies breakpoints in order, so later assignments
// override earlier ones for the same packet ID.
func GenerateLengthsFile(server ServerType, breakpoints []LengthBreakpoint) (string, error) {
	var sb strings.Builder
	sb.WriteString("// Code generated by internal/codegen. DO NOT EDIT.\n\n")
	sb.WriteString("package session\n\n")
	sb.WriteString(fmt.Sprintf("// populate%sLengths initialises the %s server packet length table\n", capitalize(string(server)), server))
	sb.WriteString("// for the given PACKETVER. Called once from New*Session constructors.\n")
	sb.WriteString("// Packet lengths: -1 = variable (read bytes [2:4]), 0 = unknown (stream fault).\n")
	sb.WriteString(fmt.Sprintf("func populate%sLengths(pv uint32, t *[65536]int16) {\n", capitalize(string(server))))

	// Sort breakpoints by Ver ascending.
	sorted := make([]LengthBreakpoint, len(breakpoints))
	copy(sorted, breakpoints)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Ver < sorted[j].Ver })

	for _, bp := range sorted {
		if len(bp.Entries) == 0 {
			continue
		}
		// Sort entries within a breakpoint by ID for deterministic output.
		sortedEntries := make([]LengthEntry, len(bp.Entries))
		copy(sortedEntries, bp.Entries)
		sort.Slice(sortedEntries, func(i, j int) bool { return sortedEntries[i].ID < sortedEntries[j].ID })

		if bp.Ver == 0 {
			// Ver==0 means "always set these" (baseline, before any PACKETVER check).
			for _, e := range sortedEntries {
				sb.WriteString(fmt.Sprintf("\tt[0x%04X] = %d\n", e.ID, e.Length))
			}
		} else {
			sb.WriteString(fmt.Sprintf("\tif pv >= %d {\n", bp.Ver))
			for _, e := range sortedEntries {
				sb.WriteString(fmt.Sprintf("\t\tt[0x%04X] = %d\n", e.ID, e.Length))
			}
			sb.WriteString("\t}\n")
		}
	}

	sb.WriteString("}\n")
	return sb.String(), nil
}

func capitalize(s string) string {
	if s == "" {
		return ""
	}
	return strings.ToUpper(s[:1]) + s[1:]
}
