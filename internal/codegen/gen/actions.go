package gen

import (
	"fmt"
	"sort"
	"strings"

	"github.com/lenaxia/rathena-client/internal/codegen/semantics"
)

// GenerateActionsFile generates the Go source for pkg/session/actions.go.
//
// It emits a SemanticAction uint16 type, one Action<PascalCase> constant per
// action in the semantic DB (sorted alphabetically), ActionUnknown = 0 as the
// first entry, and maxSemanticAction equal to the highest assigned value.
// Also emits a String() string method that returns the constant name for known
// values and "SemanticAction(N)" for unknown ones.
func GenerateActionsFile(db *semantics.DB) (string, error) {
	if db == nil {
		return "", fmt.Errorf("nil DB")
	}

	names := make([]string, 0, len(db.Actions))
	for name := range db.Actions {
		names = append(names, name)
	}
	sort.Strings(names)

	var sb strings.Builder
	sb.WriteString("// Code generated by internal/codegen. DO NOT EDIT.\n\n")
	sb.WriteString("package session\n\n")
	sb.WriteString("import \"fmt\"\n\n")
	sb.WriteString("// SemanticAction identifies a protocol-level semantic action.\n")
	sb.WriteString("// Each constant corresponds to one entry in semantics/mappings.yaml.\n")
	sb.WriteString("type SemanticAction uint16\n\n")
	sb.WriteString("const (\n")
	sb.WriteString("\tActionUnknown SemanticAction = 0\n")

	for i, name := range names {
		ident := actionNameToGoIdent(name)
		sb.WriteString(fmt.Sprintf("\tAction%s SemanticAction = %d\n", ident, i+1))
	}

	lastIdent := actionNameToGoIdent(names[len(names)-1])
	sb.WriteString(fmt.Sprintf("\n\t// maxSemanticAction is the highest assigned SemanticAction value.\n"))
	sb.WriteString(fmt.Sprintf("\t// Used to size the sendRegistry array in semantic.go.\n"))
	sb.WriteString(fmt.Sprintf("\tmaxSemanticAction SemanticAction = Action%s\n", lastIdent))
	sb.WriteString(")\n\n")

	sb.WriteString("// String returns the constant name for known SemanticAction values\n")
	sb.WriteString("// and \"SemanticAction(N)\" for unknown ones.\n")
	sb.WriteString("func (a SemanticAction) String() string {\n")
	sb.WriteString("\tswitch a {\n")
	sb.WriteString("\tcase ActionUnknown:\n\t\treturn \"ActionUnknown\"\n")
	for _, name := range names {
		ident := actionNameToGoIdent(name)
		sb.WriteString(fmt.Sprintf("\tcase Action%s:\n\t\treturn \"Action%s\"\n", ident, ident))
	}
	sb.WriteString("\t}\n")
	sb.WriteString("\treturn fmt.Sprintf(\"SemanticAction(%d)\", uint16(a))\n")
	sb.WriteString("}\n")

	return sb.String(), nil
}
