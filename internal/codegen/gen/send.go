package gen

import (
	"fmt"
	"sort"
	"strings"

	"github.com/lenaxia/rathena-client/internal/codegen/preprocess"
	"github.com/lenaxia/rathena-client/internal/codegen/semantics"
)

// SendInput describes a single semantic action to generate a send request struct for.
type SendInput struct {
	Action       *semantics.Action
	VersionTable preprocess.VersionTable
}

// GenerateSendFile generates the Go source for pkg/send/<action_name>.go.
//
// The request struct fields are derived directly from the rAthena struct layout
// of the first send-direction implementation. Field names use the rAthena C field
// names (capitalised to exported Go identifiers). PacketType is excluded.
func GenerateSendFile(input SendInput) (filename string, src string, err error) {
	a := input.Action
	if a == nil {
		return "", "", fmt.Errorf("nil action")
	}
	if a.Name == "" {
		return "", "", fmt.Errorf("action has empty name")
	}

	structName := actionNameToGoIdent(a.Name)
	filename = actionNameToFilename(a.Name)

	// Collect fields from send-direction struct.
	fields := sendFields(a, input.VersionTable)

	var sb strings.Builder
	sb.WriteString("// Code generated by internal/codegen. DO NOT EDIT.\n\n")
	sb.WriteString("package send\n\n")
	sb.WriteString(fmt.Sprintf("// %s is the request struct for the %s action.\n", structName, a.Name))
	sb.WriteString(fmt.Sprintf("type %s struct {\n", structName))

	for _, ef := range fields {
		sb.WriteString(fmt.Sprintf("\t%s %s\n", ef.GoName, ef.GoType))
	}

	sb.WriteString("}\n")
	return filename, sb.String(), nil
}

// sendFields collects the fields from the first resolvable send-direction implementation.
// For structs that contain a flex array payload the packetLength/packetSize field is
// excluded — the encoder computes it internally from len(p), so callers must not set it.
func sendFields(a *semantics.Action, vt preprocess.VersionTable) []eventField {
	seen := make(map[string]string)
	var ordered []eventField

	for _, impl := range a.Implementations {
		if !isSendStruct(impl.StructName) {
			continue
		}
		layout := resolveLayout(impl.StructName, impl.PacketverMin, vt)
		if layout == nil {
			continue
		}
		flex := hasFlexField(layout)
		for i := range layout.Fields {
			f := &layout.Fields[i]
			if f.Name == "PacketType" || f.Name == "packetType" || f.Name == "packet_type" {
				continue
			}
			// Strip the wire-length field from flex-array structs — the encoder
			// computes it as uint16(len(p)) rather than reading from the caller.
			if flex && isLengthField(f.Name) {
				continue
			}
			goName := cFieldToGoIdent(f.Name)
			goType := cTypeToGoType(f)
			if _, exists := seen[goName]; !exists {
				seen[goName] = goType
				ordered = append(ordered, eventField{GoName: goName, GoType: goType})
			}
		}
		// Use just the first resolvable send implementation for the struct shape.
		if len(ordered) > 0 {
			break
		}
	}

	return ordered
}

// GenerateSendDirFiles generates all send request files from a semantics DB + VersionTable.
// Only C→S actions (implementations with CZ_/CH_/CA_/SYNTH_CZ_ struct names) are included.
func GenerateSendDirFiles(db *semantics.DB, vt preprocess.VersionTable) (map[string]string, error) {
	if db == nil {
		return nil, fmt.Errorf("nil DB")
	}

	result := make(map[string]string)

	names := make([]string, 0, len(db.Actions))
	for name := range db.Actions {
		names = append(names, name)
	}
	sort.Strings(names)

	for _, name := range names {
		action := db.Actions[name]
		if len(action.Implementations) == 0 {
			continue
		}

		// Only generate send types for C→S packets.
		isSend := false
		for _, impl := range action.Implementations {
			if isSendStruct(impl.StructName) {
				isSend = true
				break
			}
		}
		if !isSend {
			continue
		}

		filename, src, err := GenerateSendFile(SendInput{Action: action, VersionTable: vt})
		if err != nil {
			return nil, fmt.Errorf("action %s: %w", name, err)
		}

		// Deduplicate: skip if identical content already exists under a different action.
		_ = strings.TrimSpace(src) // ensure non-nil
		result[filename] = src
	}

	return result, nil
}
