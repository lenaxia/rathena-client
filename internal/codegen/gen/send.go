package gen

import (
	"fmt"
	"sort"
	"strings"

	"github.com/lenaxia/ragnarok-go-client/internal/codegen/semantics"
)

// SendInput describes a single semantic action to generate a send request struct for.
type SendInput struct {
	Action *semantics.Action
}

// GenerateSendFile generates the Go source for pkg/send/<action_name>.go.
//
// Each file contains a single exported request struct whose fields are derived
// from the action's canonical_params. Only C→S actions (implementations with
// PACKET_CZ_, PACKET_CH_, or PACKET_CA_ struct names) should be passed here.
//
// The generated package is "send".
func GenerateSendFile(input SendInput) (filename string, src string, err error) {
	a := input.Action
	if a == nil {
		return "", "", fmt.Errorf("nil action")
	}
	if a.Name == "" {
		return "", "", fmt.Errorf("action has empty name")
	}

	structName := actionNameToGoIdent(a.Name)
	filename = actionNameToFilename(a.Name)

	var sb strings.Builder
	sb.WriteString("// Code generated by internal/codegen. DO NOT EDIT.\n\n")
	sb.WriteString("package send\n\n")

	if a.Description != "" {
		sb.WriteString(fmt.Sprintf("// %s is the request struct for the %s action.\n", structName, a.Name))
		sb.WriteString(fmt.Sprintf("// %s\n", a.Description))
	}
	sb.WriteString(fmt.Sprintf("type %s struct {\n", structName))

	for _, p := range a.CanonicalParams {
		if p.Name == "" {
			continue
		}
		fieldName := paramNameToGoIdent(p.Name)
		goType := normaliseGoType(p.Type)
		comment := ""
		if p.Semantic != "" {
			comment = " // " + sanitiseComment(p.Semantic)
		}
		sb.WriteString(fmt.Sprintf("\t%s %s%s\n", fieldName, goType, comment))
	}

	sb.WriteString("}\n")

	return filename, sb.String(), nil
}

// GenerateSendDirFiles generates all send request files from a semantics DB.
// Returns a map of filename → Go source string.
// Only C→S actions (implementations with CZ_/CH_/CA_ struct names) are included.
func GenerateSendDirFiles(db *semantics.DB) (map[string]string, error) {
	if db == nil {
		return nil, fmt.Errorf("nil DB")
	}

	result := make(map[string]string)

	names := make([]string, 0, len(db.Actions))
	for name := range db.Actions {
		names = append(names, name)
	}
	sort.Strings(names)

	for _, name := range names {
		action := db.Actions[name]
		if len(action.Implementations) == 0 {
			continue
		}

		// Only generate send types for C→S packets.
		isSend := false
		for _, impl := range action.Implementations {
			if strings.HasPrefix(impl.StructName, "PACKET_CZ_") ||
				strings.HasPrefix(impl.StructName, "PACKET_CH_") ||
				strings.HasPrefix(impl.StructName, "PACKET_CA_") {
				isSend = true
				break
			}
		}
		if !isSend {
			continue
		}

		if len(action.CanonicalParams) == 0 {
			// Generate an empty struct for zero-param send actions (e.g. keepalive).
		}

		filename, src, err := GenerateSendFile(SendInput{Action: action})
		if err != nil {
			return nil, fmt.Errorf("action %s: %w", name, err)
		}
		result[filename] = src
	}

	return result, nil
}
